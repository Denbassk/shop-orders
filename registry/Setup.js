/**
 * Создание структуры справочника ТТ. Запустить ОДИН раз.
 */
function setupRegistry() {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const ui = SpreadsheetApp.getUi();
  let sh = ss.getSheetByName(REGISTRY_SHEET);

  if (sh && sh.getLastRow() > 1) {
    if (ui.alert('Увага', 'Лист "' + REGISTRY_SHEET + '" містить дані. Перезаписати?',
        ui.ButtonSet.YES_NO) !== ui.Button.YES) return;
    sh.clear();
    sh.clearConditionalFormatRules();
  }
  if (!sh) sh = ss.insertSheet(REGISTRY_SHEET);

  const headers = ['Активна', 'Назва для продавця', 'Адреса (основна)',
                   'Обліковий номер', 'Маршрут', 'Тип',
                   'Хліб', 'Випічка', 'Овочі', 'Примітка',
                   'Адреса в табл. Хліб', 'Адреса в табл. Випічка', 'Адреса в табл. Овочі'];

  sh.getRange(1, 1, 1, headers.length).setValues([headers])
    .setFontWeight('bold').setBackground('#1a73e8').setFontColor('#ffffff')
    .setVerticalAlignment('middle').setWrap(true);
  sh.getRange(1, 11, 1, 3).setBackground('#5f6368');

  const rows = getInitialStores_();
  sh.getRange(2, 1, rows.length, headers.length).setValues(rows);

  sh.getRange(2, 1, rows.length, 1).insertCheckboxes();
  sh.getRange(2, 7, rows.length, 3).insertCheckboxes();

  sh.getRange(2, 6, rows.length, 1).setDataValidation(
    SpreadsheetApp.newDataValidation()
      .requireValueInList(['Магазин', 'Виробництво'], true)
      .setAllowInvalid(false).build());

  sh.getRange(2, 4, sh.getMaxRows() - 1, 1).setNumberFormat('@');

  [70, 210, 320, 110, 110, 115, 60, 70, 60, 250, 250, 250, 250]
    .forEach((w, i) => sh.setColumnWidth(i + 1, w));

  sh.setFrozenRows(1);
  sh.setFrozenColumns(2);
  sh.getRange(2, 7, sh.getMaxRows() - 1, 3).setHorizontalAlignment('center');
  sh.getRange(1, 1, sh.getMaxRows(), headers.length).setVerticalAlignment('middle');
  sh.getRange(2, 11, sh.getMaxRows() - 1, 3).setFontColor('#80868b').setFontSize(9);

  sh.setConditionalFormatRules([
    SpreadsheetApp.newConditionalFormatRule()
      .whenFormulaSatisfied('=$A2=FALSE')
      .setBackground('#f1f3f4').setFontColor('#9aa0a6')
      .setRanges([sh.getRange(2, 1, sh.getMaxRows() - 1, headers.length)]).build(),
    SpreadsheetApp.newConditionalFormatRule()
      .whenFormulaSatisfied('=$F2="Виробництво"')
      .setBackground('#fff3e0')
      .setRanges([sh.getRange(2, 1, sh.getMaxRows() - 1, headers.length)]).build()
  ]);

  sh.getRange('K1:M1').setNote(
    'Заповнюється ЛИШЕ якщо в робочій таблиці адреса написана інакше, ніж у колонці C. ' +
    'Порожньо = використовується адреса з колонки C. Не змінюйте без потреби: ' +
    'за цими рядками звіти знаходять історичні замовлення.');

  ui.alert('Готово', 'Створено ' + rows.length + ' рядків з маршрутами та обліковими номерами.\n\n' +
    'Далі: меню "Довідник ТТ" → пункт 1, потім пункт 2.', ui.ButtonSet.OK);
}

