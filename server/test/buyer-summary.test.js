test('Овочі: нова розкладка колонок (Сума перед Кількістю) читається за шапкою; стара - теж', () => {
  const head = ['№', 'Назва овочу', 'Ціна/кг', 'Сума, грн', 'Кількість, кг'];
  const orders = [['Замовлення'], ['ТТ із замовленнями: 4 з 5'], head, ['ЗАГАЛЬНИЙ ПІДСУМОК', '', '', '2 881,00', '94']];
  const summary = [head, ['1', 'Картопля', '17,00', '833,00', '49'], ['ЗАГАЛОМ', '', '', '2 881,00', '94']];
  const d = SUM.veg({ orders, summary });
  assert.deepEqual([d.top[0].qty, d.top[0].sum], [49, 833]);
  assert.equal(d.stats.find((x) => x.k === 'кг').v, '94');
  assert.equal(d.stats.find((x) => x.k === 'гривень').v.replace(/\s/g, ''), '2881');
  const old = ['№', 'Назва овочу', 'Ціна/кг', 'Кількість, кг', 'Сума, грн'];
  const d2 = SUM.veg({ orders: [['Замовлення'], old, ['ЗАГАЛЬНИЙ ПІДСУМОК', '', '', '94', '2 881,00']], summary: [old, ['1', 'Картопля', '17,00', '49', '833,00']] });
  assert.deepEqual([d2.top[0].qty, d2.top[0].sum], [49, 833]);
});
